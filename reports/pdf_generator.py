"""
Printable Document & Summary Report Generator Module.

Purpose:
Generates structured text and printable HTML summaries for store executives and Viva demonstrations.

Why this file exists:
Provides clean, formatted document generation without requiring heavyweight external PDF binaries.
"""

from typing import Dict, Any, List
from datetime import datetime, timezone


class DocumentReportGenerator:
    """Produces clean formatted audit summaries for print and executive inspection."""

    @staticmethod
    def generate_executive_summary_text(
        revenue_metrics: Dict[str, Any],
        inventory_summary: Dict[str, Any],
    ) -> str:
        """
        Creates a clean plain-text financial and stock intelligence audit summary.

        Returns:
            str: Monospace-formatted executive memorandum.
        """
        timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        return f"""
================================================================================
 RETAIL STOCK OPTIMIZATION AND SALES INTELLIGENCE PLATFORM
 EXECUTIVE AUDIT MEMORANDUM - {timestamp}
================================================================================

1. FINANCIAL PERFORMANCE METRICS:
   - Cumulative Gross Sales Revenue:   ${revenue_metrics.get('total_revenue', 0.0):,.2f}
   - Total Sales Transactions:          {revenue_metrics.get('total_transactions', 0):,}
   - Total Physical Units Sold:         {revenue_metrics.get('total_units_sold', 0):,}
   - Average Order Value (AOV):        ${revenue_metrics.get('average_order_value', 0.0):,.2f}

2. INVENTORY HEALTH & CAPITAL ALLOCATION:
   - Total Catalog Products:            {inventory_summary.get('total_products', 0)}
   - Total Units on Shelves:            {inventory_summary.get('total_inventory_units', 0):,}
   - Total Inventory Asset Valuation:  ${inventory_summary.get('total_inventory_asset_value', 0.0):,.2f}
   - Products Needing Reorder:          {inventory_summary.get('low_stock_alerts_count', 0)}
   - Catalog Stock Availability Rate:   {inventory_summary.get('inventory_health_percentage', 100.0)}%

================================================================================
 End of Memorandum - Generated by RetailPulse Platform
================================================================================
""".strip()
