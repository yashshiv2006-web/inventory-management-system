"""
Product Service Module.

Why this file exists:
In a service-oriented architectural pattern, the "Service Layer" encapsulates all the
core business logic, domain rules, and database operations for a specific domain entity.
Routes (controllers) should never write database queries or execute business decisions directly;
they should always delegate those tasks to a Service class like ProductService.
"""

from typing import List, Dict, Any, Optional
from database.db import db
from models.product import Product
from models.inventory import Inventory
from utils.helpers import ResourceNotFoundError, DuplicateResourceError, ValidationError


class ProductService:
    """
    Encapsulates all business logic for managing retail products.
    Follows Object-Oriented Programming (OOP) and Single Responsibility Principle (SRP).
    """

    @staticmethod
    def add_product(
        name: str,
        price: float,
        category: str,
        sku: str,
        description: str = "",
        initial_stock: int = 0,
        low_stock_threshold: int = 10,
        created_by_user_id: Optional[int] = None,
        supplier_id: Optional[int] = None,
    ) -> Product:
        """
        Creates a new product in the catalog and initializes its inventory record.

        Business Rules:
        1. SKU must be unique across the entire store catalog.
        2. Price must be strictly positive (> 0).
        3. Name and Category must not be empty.
        4. Every newly registered product automatically receives an associated Inventory record.

        Args:
            name (str): Product title.
            price (float): Base selling price per unit.
            category (str): Department category.
            sku (str): Unique Stock Keeping Unit barcode.
            description (str, optional): Product details. Defaults to "".
            initial_stock (int, optional): Initial shelf units. Defaults to 0.
            low_stock_threshold (int, optional): Restock threshold alert. Defaults to 10.

        Returns:
            Product: The newly created and committed Product ORM object.

        Raises:
            ValidationError: If input validation rules fail.
            DuplicateResourceError: If the SKU is already in use by another product.
        """
        # Step 1: Input hygiene and normalization
        clean_sku = str(sku).strip().upper()
        clean_name = str(name).strip()
        clean_category = str(category).strip()

        if not clean_sku or not clean_name or not clean_category:
            raise ValidationError("Product SKU, Name, and Category cannot be empty.")

        if price <= 0:
            raise ValidationError("Product price must be greater than zero.")

        # Step 2: Uniqueness check - verify no existing product shares this SKU
        existing_product = Product.query.filter_by(sku=clean_sku).first()
        if existing_product:
            raise DuplicateResourceError(
                f"A product with SKU '{clean_sku}' already exists (ID: {existing_product.id})."
            )

        try:
            # Step 3: Instantiate the Product ORM entity
            new_product = Product(
                sku=clean_sku,
                name=clean_name,
                category=clean_category,
                price=price,
                description=description,
                created_by_user_id=created_by_user_id,
                supplier_id=supplier_id,
            )

            # Add to the current SQLAlchemy transaction session
            db.session.add(new_product)

            # Flush the session so that `new_product.id` is generated by the database
            db.session.flush()

            # Step 4: Automatically initialize the associated Inventory ledger entry
            new_inventory = Inventory(
                product_id=new_product.id,
                quantity=max(0, int(initial_stock)),
                low_stock_threshold=max(0, int(low_stock_threshold)),
            )
            db.session.add(new_inventory)

            # Step 5: Commit both the Product and Inventory records atomically
            db.session.commit()

            return new_product

        except Exception as e:
            # If any database error occurs, rollback all pending changes to keep DB consistent
            db.session.rollback()
            raise e

    @staticmethod
    def get_product_by_id(product_id: int) -> Product:
        """
        Fetches a single product by its database ID.

        Args:
            product_id (int): Primary key of the product.

        Returns:
            Product: The matched Product instance.

        Raises:
            ResourceNotFoundError: If no product matches the provided ID.
        """
        product = db.session.get(Product, product_id)
        if not product:
            raise ResourceNotFoundError(f"Product with ID {product_id} was not found.")
        return product

    @staticmethod
    def update_product(product_id: int, **kwargs: Any) -> Product:
        """
        Updates product attributes (e.g. name, price, category, description, sku).

        Business Rules:
        1. Product must exist.
        2. Price must remain > 0 if updated.
        3. If SKU is being updated, it must not collide with an existing product.

        Args:
            product_id (int): ID of the product to update.
            **kwargs: Arbitrary keyword arguments containing fields to update.

        Returns:
            Product: The updated Product instance.

        Raises:
            ResourceNotFoundError: If the product does not exist.
            ValidationError: If updated values are invalid.
            DuplicateResourceError: If the new SKU is already taken.
        """
        # Step 1: Retrieve the target product
        product = ProductService.get_product_by_id(product_id)

        try:
            # Step 2: Handle SKU update with uniqueness validation
            if "sku" in kwargs and kwargs["sku"]:
                new_sku = str(kwargs["sku"]).strip().upper()
                if new_sku != product.sku:
                    sku_conflict = Product.query.filter(
                        Product.sku == new_sku, Product.id != product_id
                    ).first()
                    if sku_conflict:
                        raise DuplicateResourceError(
                            f"Cannot change SKU to '{new_sku}'; it is already assigned to another product."
                        )
                    product.sku = new_sku

            # Step 3: Handle Name update
            if "name" in kwargs and kwargs["name"]:
                clean_name = str(kwargs["name"]).strip()
                if not clean_name:
                    raise ValidationError("Product name cannot be empty.")
                product.name = clean_name

            # Step 4: Handle Category update
            if "category" in kwargs and kwargs["category"]:
                clean_cat = str(kwargs["category"]).strip()
                if not clean_cat:
                    raise ValidationError("Product category cannot be empty.")
                product.category = clean_cat

            # Step 5: Handle Price update
            if "price" in kwargs and kwargs["price"] is not None:
                new_price = float(kwargs["price"])
                if new_price <= 0:
                    raise ValidationError("Product price must be greater than zero.")
                product.price = new_price

            # Step 6: Handle Description update
            if "description" in kwargs and kwargs["description"] is not None:
                product.description = str(kwargs["description"]).strip()

            # Step 7: Handle Supplier assignment update
            if "supplier_id" in kwargs:
                product.supplier_id = int(kwargs["supplier_id"]) if kwargs["supplier_id"] else None

            # Step 8: Commit the changes
            db.session.commit()
            return product

        except Exception as e:
            db.session.rollback()
            raise e

    @staticmethod
    def delete_product(product_id: int) -> bool:
        """
        Deletes a product from the catalog. Cascading rules also remove
        the associated inventory record.

        Args:
            product_id (int): ID of the product to remove.

        Returns:
            bool: True if deletion was successful.

        Raises:
            ResourceNotFoundError: If the product does not exist.
        """
        product = ProductService.get_product_by_id(product_id)

        try:
            db.session.delete(product)
            db.session.commit()
            return True
        except Exception as e:
            db.session.rollback()
            raise e

    @staticmethod
    def search_product(keyword: str) -> List[Product]:
        """
        Performs a case-insensitive search across Product name, category, and SKU.

        Args:
            keyword (str): The search query string.

        Returns:
            List[Product]: List of matching Product instances.
        """
        clean_kw = str(keyword).strip()
        if not clean_kw:
            # If the search query is blank, return all products
            return ProductService.list_products()

        search_filter = f"%{clean_kw}%"
        results = Product.query.filter(
            (Product.name.ilike(search_filter))
            | (Product.category.ilike(search_filter))
            | (Product.sku.ilike(search_filter))
        ).all()

        return results

    @staticmethod
    def list_products() -> List[Product]:
        """
        Retrieves all products registered in the retail platform.

        Returns:
            List[Product]: Full list of products ordered by ID.
        """
        return Product.query.order_by(Product.id.asc()).all()
